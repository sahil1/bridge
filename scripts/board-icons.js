#!/usr/bin/env node
// Copies the icons the whiteboard's shapes use (shared/whiteboard/catalog.js) out of Tabler Icons
// (MIT, a dev dependency) into src/components/whiteboard/shapes/icons.js. Importing the package
// would put all ~6,000 icons in the app. Run `npm run icons:boards` after adding a glyph to the
// catalog. A network switch has no Tabler icon, so it's drawn here in the same style.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { SETS } from '../shared/whiteboard/catalog.js'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const DIR = path.join(ROOT, 'node_modules', '@tabler', 'icons', 'icons', 'outline')
const OUT = path.join(ROOT, 'src', 'components', 'whiteboard', 'shapes', 'icons.js')
// Drawn here: 24 by 24, a 2px line, as Tabler's are.
const OWN = {
  'net-switch': '<path d="M3 15a2 2 0 0 1 2 -2h14a2 2 0 0 1 2 2v4a2 2 0 0 1 -2 2h-14a2 2 0 0 1 -2 -2z"/><path d="M7 17h.01M11 17h.01M15 17h.01"/><path d="M5 5h13M15 2l3 3l-3 3"/><path d="M19 9h-13M9 6l-3 3l3 3"/>',
}

const names = new Set()
for (const s of SETS) {
  if (s.brand) names.add(s.brand)
  for (const it of s.items) if (it.glyph) names.add(it.glyph)
}
const out = {}
for (const n of [...names].sort()) {
  if (OWN[n]) { out[n] = OWN[n]; continue }
  const file = path.join(DIR, `${n}.svg`)
  if (!fs.existsSync(file)) throw new Error(`Tabler Icons has no ${n}`)
  // The drawing inside the <svg>, without the invisible square Tabler starts each with.
  const inner = fs.readFileSync(file, 'utf8').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
    .replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/, '').replace(/\s*\n\s*/g, '').trim()
  out[n] = inner
}
const version = JSON.parse(fs.readFileSync(path.join(ROOT, 'node_modules', '@tabler', 'icons', 'package.json'), 'utf8')).version
// The icons' license goes with them, as MIT asks.
const license = fs.readFileSync(path.join(ROOT, 'node_modules', '@tabler', 'icons', 'LICENSE'), 'utf8').trim().split('\n').map((l) => ` * ${l}`.trimEnd()).join('\n')
fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, `// Generated by scripts/board-icons.js from Tabler Icons ${version} (https://tabler.io/icons). Don't edit by hand.\n// Each is the inside of a 24 by 24 SVG drawn with a 2px line in currentColor.\n/*! Tabler Icons\n${license}\n */\nexport const GLYPHS = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n  "').replace(/^\{"/, '{\n  "').replace(/"\}$/, '",\n}')}\n`)
console.log(`Wrote ${Object.keys(out).length} icons to ${path.relative(process.cwd(), OUT)}`)
