#!/usr/bin/env node
// Copies the few brand marks Bridge AI shows (providers and agent CLIs) out of simple-icons into
// src/components/settings/brandIcons.js. Importing simple-icons itself would put all ~3,000 marks
// (about 5 MB) in the app. Run `npm run icons:brands` after adding a brand to the list below.
// Simple Icons is CC0; trademarks belong to their owners (see NOTICE).
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import * as si from 'simple-icons'

const NAMES = ['siAnthropic', 'siClaude', 'siGooglegemini', 'siMistralai', 'siDeepseek', 'siPerplexity', 'siKimi', 'siZdotai',
  'siGooglecloud', 'siOpenrouter', 'siHuggingface', 'siOllama', 'siLmstudio', 'siGithubcopilot', 'siCursor', 'siQwen', 'siOpencode', 'siMeta']

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'components', 'settings', 'brandIcons.js')
const lines = NAMES.map((n) => {
  const i = si[n]
  if (!i) throw new Error(`simple-icons has no ${n}`)
  return `export const ${n} = ${JSON.stringify({ title: i.title, hex: i.hex, path: i.path })}`
})
fs.writeFileSync(out, `// Generated by scripts/brand-icons.js from simple-icons ${JSON.parse(fs.readFileSync(new URL('../node_modules/simple-icons/package.json', import.meta.url))).version} (CC0). Don't edit by hand.\n${lines.join('\n')}\n`)
console.log(`Wrote ${NAMES.length} marks to ${path.relative(process.cwd(), out)}`)
